export const getClothingById = (id) => clothing.find((c) => c.id === id)

export const filterClothing = ({ category, color, occasion, search }) =>
  clothing.filter((item) => {
    if (category && category !== 'all' && item.category !== category) return false
    if (color && color !== 'all' && item.color !== color) return false
    if (occasion && occasion !== 'all' && !item.occasion.includes(occasion)) return false
    if (search) {
      const q = search.toLowerCase()
      if (!item.name.toLowerCase().includes(q) && !item.tags?.some((t) => t.includes(q))) return false
    }
    return true
  })
